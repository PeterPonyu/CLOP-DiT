def run_cross_dataset_validation() -> dict:
    """Run gene-level cross-dataset validation per tissue dataset.

    For each of the 5 biovalidation datasets, compare gene expression
    distributions between the external tissue data and generated cells.
    Metrics: per-gene Spearman correlation, mean expression Pearson r,
    variance ratio, and PCA subspace overlap (Grassmann distance).
    """
    import scanpy as sc
    from scipy import stats as scipy_stats

    datasets_path = _PROJECT_ROOT / "configs" / "biovalidation_datasets.json"
    with open(datasets_path) as f:
        datasets = json.load(f)

    # Load generated expression data
    gen_expr = np.load(RESULTS_DIR / "generated_expression.npy")
    with open(RESULTS_DIR / "expression_gene_names.json") as f:
        gen_gene_names = json.load(f)
    gen_gene_set = set(gen_gene_names)

    tissue_results = {}
    for ds in datasets:
        tissue = ds["tissue"]
        h5ad_path = _PROJECT_ROOT / ds["reference_h5ad"]
        logger.info(f"Cross-dataset validation: {tissue} ({h5ad_path.name})")

        if not h5ad_path.exists():
            logger.warning(f"  h5ad not found: {h5ad_path}, skipping")
            continue

        try:
            ref = sc.read_h5ad(h5ad_path)
        except Exception as e:
            logger.warning(f"  Failed to read {h5ad_path}: {e}")
            continue

        # Find overlapping genes
        ref_genes = list(ref.var_names) if ref.var_names is not None else []
        shared_genes = sorted(set(ref_genes) & gen_gene_set)
        logger.info(f"  {tissue}: {len(ref_genes)} ref genes, {len(shared_genes)} shared")

        if len(shared_genes) < 50:
            tissue_results[tissue] = {
                "status": "insufficient_gene_overlap",
                "n_ref_genes": len(ref_genes),
                "n_shared": len(shared_genes),
                "description": ds["description"],
            }
            continue

        # Extract expression for shared genes
        ref_gene_idx = [ref_genes.index(g) for g in shared_genes]
        gen_gene_idx = [gen_gene_names.index(g) for g in shared_genes]

        ref_X = ref.X
        if hasattr(ref_X, 'toarray'):
            ref_X = ref_X.toarray()
        ref_expr = ref_X[:, ref_gene_idx].astype(np.float64)
        gen_expr_sub = gen_expr[:, gen_gene_idx].astype(np.float64)

        # 1. Per-gene mean expression correlation
        ref_mean = ref_expr.mean(axis=0)
        gen_mean = gen_expr_sub.mean(axis=0)
        pearson_r, _ = scipy_stats.pearsonr(ref_mean, gen_mean)
        spearman_r, _ = scipy_stats.spearmanr(ref_mean, gen_mean)

        # 2. Per-gene variance ratio
        ref_var = ref_expr.var(axis=0) + 1e-10
        gen_var = gen_expr_sub.var(axis=0) + 1e-10
        var_ratio = gen_var / ref_var
        median_var_ratio = float(np.median(var_ratio))

        # 3. PCA subspace overlap (Grassmann distance)
        from sklearn.decomposition import PCA
        n_pc = min(20, len(shared_genes) - 1, ref_expr.shape[0] - 1, gen_expr_sub.shape[0] - 1)
        pca_ref = PCA(n_components=n_pc, random_state=42).fit(ref_expr)
        pca_gen = PCA(n_components=n_pc, random_state=42).fit(gen_expr_sub)
        # Grassmann: principal angles between subspaces
        cos_angles = np.linalg.svd(pca_ref.components_ @ pca_gen.components_.T, compute_uv=False)
        cos_angles = np.clip(cos_angles, 0, 1)
        subspace_overlap = float(np.mean(cos_angles))

        # 4. Fraction of genes with correlated expression across cells
        gene_cors = []
        for j in range(len(shared_genes)):
            # Sample equal numbers from each
            n_sample = min(500, ref_expr.shape[0], gen_expr_sub.shape[0])
            rng = np.random.RandomState(42)
            r_idx = rng.choice(ref_expr.shape[0], n_sample, replace=False)
            g_idx = rng.choice(gen_expr_sub.shape[0], n_sample, replace=False)
            # KS test: are distributions similar?
            ks_stat, ks_p = scipy_stats.ks_2samp(ref_expr[r_idx, j], gen_expr_sub[g_idx, j])
            gene_cors.append({"gene": shared_genes[j], "ks_stat": float(ks_stat), "ks_p": float(ks_p)})
        frac_similar = sum(1 for g in gene_cors if g["ks_p"] > 0.05) / len(gene_cors)

        tissue_results[tissue] = {
            "status": "ok",
            "description": ds["description"],
            "n_ref_cells": ref.n_obs,
            "n_ref_genes": len(ref_genes),
            "n_shared_genes": len(shared_genes),
            "mean_expr_pearson_r": float(pearson_r),
            "mean_expr_spearman_r": float(spearman_r),
            "median_variance_ratio": median_var_ratio,
            "pca_subspace_overlap": subspace_overlap,
            "frac_genes_similar_distribution": float(frac_similar),
            "n_gen_cells": gen_expr.shape[0],
        }
        logger.info(f"  {tissue}: Pearson r={pearson_r:.3f}, Spearman ρ={spearman_r:.3f}, "
                     f"subspace overlap={subspace_overlap:.3f}, "
                     f"frac similar={frac_similar:.3f}")

    # Save results
    out_path = OUT_DIR / "cross_dataset_validation.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(tissue_results, f, indent=2, default=str)
    logger.info(f"Saved cross-dataset results → {out_path}")
    return tissue_results


