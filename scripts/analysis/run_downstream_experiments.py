def run_ood_robustness() -> dict:
    """Quantitative OOD evaluation using existing results + marker analysis.

    Reads pre-computed OOD results and marker analysis, then computes
    per-category summary statistics.
    """
    ood_results_path = RESULTS_DIR / "ood_evaluation" / "ood_results.json"
    marker_path = RESULTS_DIR / "ood_evaluation" / "ood_marker_analysis.json"

    results = {"novel_types": {}, "free_form": {}, "cross_tissue": {}, "summary": {}}

    # Load OOD results
    if ood_results_path.exists():
        with open(ood_results_path) as f:
            ood = json.load(f)
        results["novel_types"] = ood.get("novel_types", {})
        results["free_form"] = ood.get("free_form", {})
    else:
        logger.warning(f"OOD results not found: {ood_results_path}")

    # Load marker analysis
    if marker_path.exists():
        with open(marker_path) as f:
            markers = json.load(f)

        # Compute per-category marker statistics
        for category in ["novel_types", "free_form", "cross_tissue"]:
            cat_data = markers.get(category, {})
            hit_rates = []
            for name, info in cat_data.items():
                hr = info.get("marker_hit_rate", 0)
                hit_rates.append(hr)
                # Enrich the main results with marker data
                if name in results.get(category, {}):
                    results[category][name]["marker_hit_rate"] = hr
                    results[category][name]["markers_in_vocabulary"] = info.get("markers_in_vocabulary", 0)
                    results[category][name]["markers_upregulated"] = info.get("markers_upregulated", 0)
                    results[category][name]["expected_markers"] = info.get("expected_markers", [])
                else:
                    results[category][name] = {
                        "marker_hit_rate": hr,
                        "markers_in_vocabulary": info.get("markers_in_vocabulary", 0),
                        "markers_upregulated": info.get("markers_upregulated", 0),
                        "expected_markers": info.get("expected_markers", []),
                        "intra_sample_cosine_sim": info.get("intra_sample_cosine_sim", 0),
                    }

            if hit_rates:
                results["summary"][category] = {
                    "n_prompts": len(hit_rates),
                    "mean_marker_hit_rate": float(np.mean(hit_rates)),
                    "median_marker_hit_rate": float(np.median(hit_rates)),
                    "n_with_hits": int(sum(1 for h in hit_rates if h > 0)),
                }
    else:
        logger.warning(f"Marker analysis not found: {marker_path}")

    # Save combined results
    out_path = OUT_DIR / "ood_robustness_combined.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2, default=str)
    logger.info(f"Saved OOD robustness results → {out_path}")
    return results


