def run_marker_completeness() -> dict:
    """Compute marker gene program completeness for representative cell types.

    For each cell type in MARKER_DATABASE, check how many canonical and
    extended markers are: (a) in the gene vocabulary, (b) in the top-K
    expressed genes of generated cells, (c) differentially expressed
    vs. all other generated types.
    """
    gene_names_path = RESULTS_DIR / "expression_gene_names.json"
    gen_expr_path = RESULTS_DIR / "generated_expression.npy"
    gen_labels_path = RESULTS_DIR / "generated_expression_labels.npy"

    with open(gene_names_path) as f:
        gene_names = json.load(f)
    gene_set = set(gene_names)
    gene_name_to_idx = {g: i for i, g in enumerate(gene_names)}

    gen_expr = np.load(gen_expr_path)
    gen_labels = np.load(gen_labels_path)

    type_names = _load_type_names()
    # Build name → id mapping with fuzzy fallback
    name_to_id = {}
    for k, v in type_names.items():
        name_to_id[v] = int(k)

    def _find_type_id(query: str) -> int | None:
        """Find closest matching type ID for a query name."""
        # Exact match first
        if query in name_to_id:
            return name_to_id[query]
        # Prefix match (handles long captions)
        q_lower = query.lower()
        for name, tid in name_to_id.items():
            if name.lower().startswith(q_lower) or q_lower.startswith(name.lower()):
                return tid
        # Word overlap match
        q_words = set(q_lower.split())
        best_tid, best_score = None, 0
        for name, tid in name_to_id.items():
            n_words = set(name.lower().replace("(", "").replace(")", "").split())
            overlap = len(q_words & n_words)
            if overlap > best_score and overlap >= min(2, len(q_words)):
                best_score = overlap
                best_tid = tid
        return best_tid

    results = {}
    ks = [10, 20, 50, 100]

    for cell_type, markers in MARKER_DATABASE.items():
        type_id = _find_type_id(cell_type)
        if type_id is None:
            logger.warning(f"  Type '{cell_type}' not found in generated data")
            continue

        mask = gen_labels == type_id
        if mask.sum() == 0:
            continue

        type_expr = gen_expr[mask]
        mean_expr = type_expr.mean(axis=0)
        # Rank genes by expression in this type
        gene_ranks = np.argsort(-mean_expr)  # descending
        ranked_genes = [gene_names[i] for i in gene_ranks]

        # Background: mean expression across all other types
        bg_mask = gen_labels != type_id
        bg_expr = gen_expr[bg_mask].mean(axis=0) if bg_mask.sum() > 0 else np.zeros_like(mean_expr)
        log_fc = np.log2(mean_expr + 1) - np.log2(bg_expr + 1)

        # Analyze canonical markers
        type_result = {"n_cells": int(mask.sum())}
        for marker_set_name in ["canonical", "extended"]:
            marker_list = markers[marker_set_name]
            in_vocab = [m for m in marker_list if m in gene_set]
            not_in_vocab = [m for m in marker_list if m not in gene_set]

            # Precision@K: fraction of top-K genes that are markers
            precision_at_k = {}
            for k in ks:
                top_k = set(ranked_genes[:k])
                hits = len(top_k & set(in_vocab))
                precision_at_k[f"precision@{k}"] = hits / min(k, len(in_vocab)) if in_vocab else 0

            # Recall@K: fraction of markers found in top-K
            recall_at_k = {}
            for k in ks:
                top_k = set(ranked_genes[:k])
                hits = len(top_k & set(in_vocab))
                recall_at_k[f"recall@{k}"] = hits / len(in_vocab) if in_vocab else 0

            # Per-marker details
            marker_details = {}
            for m in marker_list:
                if m not in gene_set:
                    marker_details[m] = {"status": "not_in_vocabulary"}
                else:
                    idx = gene_name_to_idx[m]
                    rank = int(np.where(gene_ranks == idx)[0][0]) + 1
                    marker_details[m] = {
                        "rank": rank,
                        "mean_expression": float(mean_expr[idx]),
                        "log2fc_vs_background": float(log_fc[idx]),
                        "in_top_50": rank <= 50,
                        "in_top_100": rank <= 100,
                    }

            type_result[marker_set_name] = {
                "n_markers": len(marker_list),
                "n_in_vocabulary": len(in_vocab),
                "not_in_vocabulary": not_in_vocab,
                **precision_at_k,
                **recall_at_k,
                "marker_details": marker_details,
            }

        results[cell_type] = type_result

    # Save results
    out_path = OUT_DIR / "marker_completeness.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2, default=str)
    logger.info(f"Saved marker completeness results → {out_path}")
    return results


