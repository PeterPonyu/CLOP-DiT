# Experiment 5: Embedding-level augmentation
# ═══════════════════════════════════════════════════════════════════════

def run_embedding_augmentation() -> dict:
    """Test augmentation at the embedding level rather than expression level.

    Instead of decoding generated cells to expression and using that to
    augment classifiers, use the 512-d embeddings directly, which may
    better preserve cell-type structure.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import f1_score, accuracy_score
    from sklearn.model_selection import StratifiedKFold

    # Load real and generated embeddings
    cache_dir = Path("data/cached_latents_v5.2")
    real_embs = np.load(cache_dir / "cell_embeddings_dedup_preprocessed.npy")
    gen_embs = np.load(RESULTS_DIR / "generated_embeddings.npy")
    gen_labels = np.load(RESULTS_DIR / "generated_labels.npy")

    # Load real labels
    sample_ids = np.load(cache_dir / "sample_ids_dedup.npy")

    # Load type mapping from text_group
    text_group_ids = np.load(cache_dir / "text_group_ids_dedup.npy")

    type_names = _load_type_names()

    # Use text_group_ids as type labels for real embeddings
    real_labels = text_group_ids

    logger.info(f"Embedding augmentation: real={real_embs.shape}, gen={gen_embs.shape}")
    logger.info(f"Unique real types: {len(np.unique(real_labels))}, gen types: {len(np.unique(gen_labels))}")

    # Find rare types (< 50 cells)
    unique_types, type_counts = np.unique(real_labels, return_counts=True)
    rare_threshold = 50
    rare_types = unique_types[type_counts < rare_threshold]
    logger.info(f"Rare types (< {rare_threshold} cells): {len(rare_types)}")

    if len(rare_types) == 0:
        # Use bottom 10% as "rare"
        count_threshold = np.percentile(type_counts, 10)
        rare_types = unique_types[type_counts <= count_threshold]
        rare_threshold = int(count_threshold)
        logger.info(f"Adjusted: rare types (≤ {rare_threshold} cells): {len(rare_types)}")

    results = {"rare_threshold": int(rare_threshold), "n_rare_types": int(len(rare_types))}

    # Cross-validated classification: baseline vs augmented
    augmentation_ratios = [1, 5, 10]
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

    for ratio in augmentation_ratios:
        logger.info(f"  Testing augmentation ratio: {ratio}x")
        baseline_f1s = []
        augmented_f1s = []
        baseline_accs = []
        augmented_accs = []

        for fold, (train_idx, test_idx) in enumerate(cv.split(real_embs, real_labels)):
            X_train, X_test = real_embs[train_idx], real_embs[test_idx]
            y_train, y_test = real_labels[train_idx], real_labels[test_idx]

            # Baseline: train on real only
            clf_base = LogisticRegression(max_iter=2000, random_state=42, n_jobs=-1,
                                          class_weight="balanced")
            clf_base.fit(X_train, y_train)
            y_pred_base = clf_base.predict(X_test)
            baseline_f1s.append(f1_score(y_test, y_pred_base, average="macro", zero_division=0))
            baseline_accs.append(accuracy_score(y_test, y_pred_base))

            # Augmented: add generated cells for rare types
            aug_X = [X_train]
            aug_y = [y_train]
            for rt in rare_types:
                gen_mask = gen_labels == rt
                gen_rt = gen_embs[gen_mask]
                n_real = (y_train == rt).sum()
                n_aug = min(ratio * max(n_real, 1), gen_rt.shape[0])
                if n_aug > 0 and gen_rt.shape[0] > 0:
                    rng = np.random.RandomState(42 + fold)
                    idx = rng.choice(gen_rt.shape[0], size=min(n_aug, gen_rt.shape[0]), replace=False)
                    aug_X.append(gen_rt[idx])
                    aug_y.append(np.full(len(idx), rt))

            X_aug = np.vstack(aug_X)
            y_aug = np.concatenate(aug_y)

            clf_aug = LogisticRegression(max_iter=2000, random_state=42, n_jobs=-1,
                                         class_weight="balanced")
            clf_aug.fit(X_aug, y_aug)
            y_pred_aug = clf_aug.predict(X_test)
            augmented_f1s.append(f1_score(y_test, y_pred_aug, average="macro", zero_division=0))
            augmented_accs.append(accuracy_score(y_test, y_pred_aug))

        results[f"ratio_{ratio}x"] = {
            "baseline_f1_mean": float(np.mean(baseline_f1s)),
            "baseline_f1_std": float(np.std(baseline_f1s)),
            "augmented_f1_mean": float(np.mean(augmented_f1s)),
            "augmented_f1_std": float(np.std(augmented_f1s)),
            "delta_f1": float(np.mean(augmented_f1s) - np.mean(baseline_f1s)),
            "baseline_acc_mean": float(np.mean(baseline_accs)),
            "augmented_acc_mean": float(np.mean(augmented_accs)),
            "delta_acc": float(np.mean(augmented_accs) - np.mean(baseline_accs)),
        }
        logger.info(f"    Baseline F1: {np.mean(baseline_f1s):.4f} ± {np.std(baseline_f1s):.4f}")
        logger.info(f"    Augmented F1: {np.mean(augmented_f1s):.4f} ± {np.std(augmented_f1s):.4f}")
        logger.info(f"    ΔF1: {np.mean(augmented_f1s) - np.mean(baseline_f1s):+.4f}")

    # Save results
    out_path = OUT_DIR / "embedding_augmentation.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2, default=str)
    logger.info(f"Saved embedding augmentation results → {out_path}")
    return results


